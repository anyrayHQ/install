import assert from 'node:assert/strict';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { describe, test } from 'node:test';

// The desktop build caches compiled public crates in this PUBLIC repo's Actions cache, so the
// private tray's own build output must never be saved: the prune removes it and proves it.

const script = new URL('./desktop-rust-cache.mjs', import.meta.url).pathname;
const cli = (args, env = {}) => spawnSync(process.execPath, [script, ...args], { encoding: 'utf8', env: { PATH: process.env.PATH, ...env } });

const lock = (trayVersion, serdeVersion = '1.0.200') => `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "connect-tray"
version = "${trayVersion}"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "${serdeVersion}"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${'a'.repeat(64)}"
`;

const sandbox = (t) => {
  const root = mkdtempSync(join(tmpdir(), 'rust-cache-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  return root;
};

const touch = (root, file) => {
  mkdirSync(dirname(join(root, file)), { recursive: true });
  writeFileSync(join(root, file), 'x');
};

const files = (dir) => readdirSync(dir, { recursive: true, withFileTypes: true })
  .filter((e) => e.isFile())
  .map((e) => relative(dir, join(e.parentPath ?? e.path, e.name)).split('\\').join('/'))
  .sort();

describe('the cache key', () => {
  const env = { RUNNER_OS: 'Linux', TARGET_TRIPLE: 'x86_64-unknown-linux-gnu', RUST_TOOLCHAIN: '1.98.0' };
  const keyFor = (t, text) => {
    const root = sandbox(t);
    writeFileSync(join(root, 'Cargo.lock'), text);
    const out = join(root, 'out');
    writeFileSync(out, '');
    const result = cli(['key', join(root, 'Cargo.lock')], { ...env, GITHUB_OUTPUT: out });
    assert.equal(result.status, 0, result.stderr);
    return Object.fromEntries(readFileSync(out, 'utf8').trim().split('\n').map((l) => l.split('=')));
  };

  test('a tray version bump keeps the key; a dependency change moves it', (t) => {
    const a = keyFor(t, lock('0.11.346'));
    const b = keyFor(t, lock('0.11.347'));
    const c = keyFor(t, lock('0.11.347', '1.0.201'));
    assert.equal(a.key, b.key);
    assert.notEqual(b.key, c.key);
  });

  test('names the OS, target and toolchain, and the prefix is the key without the lock digest', (t) => {
    const { key, prefix } = keyFor(t, lock('1.0.0'));
    assert.equal(prefix, 'connect-desktop-v1-Linux-x86_64-unknown-linux-gnu-1.98.0-');
    assert.match(key, /^connect-desktop-v1-Linux-x86_64-unknown-linux-gnu-1\.98\.0-[0-9a-f]{64}$/);
    assert.ok(key.startsWith(prefix));
  });

  test('refuses to key without the OS, target or toolchain', (t) => {
    const root = sandbox(t);
    writeFileSync(join(root, 'Cargo.lock'), lock('1.0.0'));
    for (const name of Object.keys(env)) {
      const result = cli(['key', join(root, 'Cargo.lock')], { ...env, [name]: '', GITHUB_OUTPUT: join(root, 'out') });
      assert.notEqual(result.status, 0, `${name} missing must fail`);
      assert.match(result.stdout + result.stderr, new RegExp(name));
    }
  });
});

describe('the prune', () => {
  const keep = [
    'target/.rustc_info.json',
    'target/CACHEDIR.TAG',
    'target/release/build/serde-abc/output',
    'target/release/deps/libserde_derive-abc.so',
    'target/x86_64-unknown-linux-gnu/release/.fingerprint/serde-abc/lib-serde',
    'target/x86_64-unknown-linux-gnu/release/deps/libserde-abc.rlib',
    'target/x86_64-unknown-linux-gnu/release/deps/libtauri-abc.rlib',
  ];
  const drop = [
    // The tray itself: its compiled crate, build script output (the embedded UI), fingerprints.
    'target/release/build/connect-tray-abc/build-script-build',
    'target/x86_64-unknown-linux-gnu/release/build/connect-tray-def/out/tauri-codegen-assets/index.js',
    'target/x86_64-unknown-linux-gnu/release/.fingerprint/connect-tray-def/bin-connect-tray',
    'target/x86_64-unknown-linux-gnu/release/deps/connect_tray-def',
    'target/x86_64-unknown-linux-gnu/release/deps/connect_tray-def.d',
    // Everything else in a profile dir: final executables, sidecar copies, bundles, incremental state.
    'target/x86_64-unknown-linux-gnu/release/connect-tray',
    'target/x86_64-unknown-linux-gnu/release/anyray-connect',
    'target/x86_64-unknown-linux-gnu/release/bundle/deb/anyray.deb',
    'target/x86_64-unknown-linux-gnu/release/incremental/x/y',
    'target/x86_64-pc-windows-msvc/release/connect_tray.pdb',
  ];

  test('keeps compiled public crates and removes everything of the tray', (t) => {
    const root = sandbox(t);
    for (const f of [...keep, ...drop]) touch(root, f);
    touch(root, 'target/x86_64-pc-windows-msvc/release/deps/libserde-abc.rlib');
    const result = cli(['prune', join(root, 'target')]);
    assert.equal(result.status, 0, result.stderr);
    assert.deepEqual(files(root), [...keep, 'target/x86_64-pc-windows-msvc/release/deps/libserde-abc.rlib'].sort());
  });

  test('a missing target dir is nothing to prune', (t) => {
    const root = sandbox(t);
    const result = cli(['prune', join(root, 'target')]);
    assert.equal(result.status, 0, result.stderr);
  });

  test('tray output it cannot account for empties the whole target dir and fails', (t) => {
    const root = sandbox(t);
    for (const f of keep) touch(root, f);
    // Nested where the per-dir pass does not look: the proof must still catch it.
    touch(root, 'target/x86_64-unknown-linux-gnu/release/deps/nested/connect_tray-abc.o');
    const result = cli(['prune', join(root, 'target')]);
    assert.notEqual(result.status, 0);
    assert.match(result.stdout + result.stderr, /::error::/);
    assert.equal(existsSync(join(root, 'target')), false);
  });
});
